using SRPG.Data;

namespace SRPG.Gameplay.Campaign
{
    /// <summary>
    /// 캠페인이 전투에 건네는 주문서를 잠시 들고 있는 자리입니다.
    ///
    /// <b>왜 이런 중간 자리가 필요한가</b>
    ///
    /// 전투는 <b>다른 씬</b>에 있습니다. 씬이 열리는 순간 전투 스코프가 스스로 조립되므로,
    /// 씬을 연 뒤에 주문서를 꽂아 줄 방법이 없습니다.
    ///
    /// 예전에는 그 자리를 정적 필드가 메웠습니다. 그것이 <c>ForcedSeed</c> 였고,
    /// 정적 필드는 소유자가 없어서 언제 채워지고 언제 비워지는지가 코드에 남지 않습니다.
    ///
    /// 여기서는 캠페인 스코프가 이것을 소유합니다. 캠페인이 씬을 열기 <b>전에</b> 채우고,
    /// 전투 스코프는 조립하면서 부모 컨테이너에서 이것을 꺼냅니다.
    /// 부모는 이미 조립을 마친 상태이므로 순서가 보장됩니다.
    ///
    /// <b>왜 전투가 컨테이너에서 주문서를 직접 꺼내지 않는가</b>
    ///
    /// 캠페인 스코프는 판이 바뀌어도 살아 있습니다. 주문서를 그대로 등록해 두면
    /// 지난 판의 주문서가 다음 판까지 남아, 아무도 채우지 않았을 때 조용히 재사용됩니다.
    /// 꺼낼 때 비우면 그런 일이 생기지 않습니다.
    /// </summary>
    public sealed class BattleOrders
    {
        // ====================================================================================================
        // 1. Properties
        // ====================================================================================================

        /// <summary>다음 전투에 쓸 주문서입니다. 아직 정해지지 않았으면 null입니다.</summary>
        public BattleRequest Pending { get; private set; }

        /// <summary>이 주문서가 나온 월드맵 지점 번호입니다. 결과를 돌려줄 자리입니다.</summary>
        public int OriginNode { get; private set; } = -1;

        // ====================================================================================================
        // 2. Public Methods
        // ====================================================================================================

        /// <summary>다음 전투의 주문서를 올려 둡니다.</summary>
        /// <param name="request">전투에 넘길 주문서입니다.</param>
        /// <param name="originNode">이 전투가 벌어질 월드맵 지점 번호입니다.</param>
        public void Place(BattleRequest request, int originNode)
        {
            Pending = request;
            OriginNode = originNode;
        }

        /// <summary>
        /// 올려 둔 주문서를 가져가면서 자리를 비웁니다.
        ///
        /// <b>한 번만 가져갈 수 있습니다.</b> 그래야 캠페인이 채우지 않은 채 전투 씬이 열렸을 때
        /// 지난 판의 주문서가 조용히 다시 쓰이지 않습니다.
        /// </summary>
        /// <returns>올려 둔 주문서입니다. 없으면 null입니다.</returns>
        public BattleRequest Take()
        {
            var taken = Pending;

            Pending = null;

            return taken;
        }
    }
}
