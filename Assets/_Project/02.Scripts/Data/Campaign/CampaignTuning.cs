using UnityEngine;

namespace SRPG.Data
{
    /// <summary>
    /// 판과 판 <b>사이</b>에 걸리는 규칙입니다 — 무엇을 데리고 나갈 수 있는가.
    ///
    /// <b>왜 성장 규칙과 나누는가</b>
    ///
    /// <see cref="CampaignProgression"/> 은 <b>전투가 남긴 것을 어떻게 옮기는가</b>입니다.
    /// 여기는 <b>다음 전투에 무엇을 데리고 나가는가</b>이고, 둘은 서로를 보지 않고 조정됩니다.
    /// 한 곳에 두면 출진 상한을 만지려고 숙련도 곡선을 지나쳐야 합니다.
    ///
    /// <b>왜 스크립터블 오브젝트가 아닌가</b>
    ///
    /// <see cref="CampaignProgression"/> 과 같은 이유입니다. 한 벌만 있으면 되고,
    /// 에셋으로 만들면 "연결하는 것을 잊어 상한이 사라진" 상태가 생깁니다.
    /// 필드 초기값이 그대로 기본 규칙이 되므로 비워 두어도 캠페인이 굴러갑니다.
    /// </summary>
    [System.Serializable]
    public sealed class CampaignTuning
    {
        // ====================================================================================================
        // 1. Inspector
        // ====================================================================================================

        [Header("출진")]
        [Range(1, 8)]
        [Tooltip("한 전투에 데리고 나갈 수 있는 분대 수입니다.\n" +
                 "거느린 부대가 이보다 많아지면 그때부터 <b>고르는 일</b>이 생깁니다.\n\n" +
                 "전장 동시 전개 상한(BattleTuning.Deployment.FieldSquadCap)과 다른 값입니다 — " +
                 "저쪽은 데려간 부대 중 몇이 한 번에 서는지이고, 이쪽은 애초에 몇을 데려가는지입니다.")]
        public int MarchSquadCap = 3;

        [Range(1, 4)]
        [Tooltip("출진에 최소한 데리고 나가야 하는 분대 수입니다.\n" +
                 "0으로 둘 수 없습니다 — 아무도 없이 전장에 들어서면 시작하자마자 패배합니다.")]
        public int MinMarchSquads = 1;

        // ====================================================================================================
        // 2. Public Methods
        // ====================================================================================================

        /// <summary>
        /// 실제로 적용할 출진 상한입니다.
        ///
        /// 최소치가 상한보다 크게 적혀 있으면 <b>아무도 출진할 수 없는 규칙</b>이 되므로,
        /// 그런 조합이 들어와도 최소치가 이깁니다. 인스펙터에서 한 번 잘못 적으면
        /// 증상이 "이동 버튼이 안 눌린다" 하나뿐이라 원인을 찾기 어렵습니다.
        /// </summary>
        /// <returns>1 이상의 출진 상한입니다.</returns>
        public int ResolveMarchCap()
        {
            return Mathf.Max(ResolveMinimum(), Mathf.Max(1, MarchSquadCap));
        }

        /// <summary>실제로 적용할 최소 출진 수입니다.</summary>
        /// <returns>1 이상의 최소 출진 수입니다.</returns>
        public int ResolveMinimum()
        {
            return Mathf.Max(1, MinMarchSquads);
        }
    }
}
