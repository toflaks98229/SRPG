using UnityEngine;

namespace SRPG.Data
{
    /// <summary>
    /// 절차적 섬 생성 파라미터입니다.
    /// 생성 알고리즘 자체는 <c>SRPG.Systems.Grid.IslandGenerator</c>에 있으며, 이 에셋은 순수 데이터만 담습니다.
    /// </summary>
    [CreateAssetMenu(fileName = "IslandSettings_", menuName = "SRPG/Definitions/Island Settings")]
    public sealed class IslandSettings : ScriptableObject
    {
        // ====================================================================================================
        // 1. Grid Shape
        // ====================================================================================================

        [Header("격자")]
        [Range(12, 64)]
        [Tooltip("격자의 가로 칸 수입니다.")]
        public int Width = 30;

        [Range(12, 64)]
        [Tooltip("격자의 세로 칸 수입니다.")]
        public int Depth = 30;

        [Min(0.5f)]
        [Tooltip("타일 한 칸의 월드 크기입니다.")]
        public float CellSize = 2f;

        [Min(0.1f)]
        [Tooltip("높이 한 단계의 월드 높이입니다.\n\n" +
                 "유닛 키가 1이므로 한 단이 그보다 높으면 뒤에 선 유닛이 가립니다. " +
                 "다만 너무 얕으면 절벽이 턱으로 보여 '못 오르는 벽'으로 읽히지 않습니다.")]
        public float HeightStep = 0.7f;

        [Range(1, 8)]
        [Tooltip("최대 고도 단계입니다. 값이 클수록 섬이 계단형으로 높아집니다.\n\n" +
                 "섬이 납작하면 절벽이 생길 수가 없습니다. 폭에 비해 충분히 솟아야 " +
                 "판과 판 사이에 오를 수 없는 면이 섭니다.")]
        public int MaxHeightLevel = 6;

        // ====================================================================================================
        // 2. Island Silhouette
        // ====================================================================================================

        [Header("섬 윤곽")]
        [Range(0.15f, 0.5f)]
        [Tooltip("격자 크기 대비 섬의 기본 반경 비율입니다.")]
        public float IslandRadius = 0.36f;

        [Min(0.5f)]
        [Tooltip("윤곽을 흐트러뜨리는 노이즈의 주파수입니다. 클수록 해안선이 잘게 들쭉날쭉해집니다.")]
        public float NoiseScale = 4.5f;

        [Range(0f, 0.5f)]
        [Tooltip("윤곽 노이즈의 세기입니다. 0이면 완전한 원형 섬이 됩니다.")]
        public float NoiseStrength = 0.16f;

        // ====================================================================================================
        // 2-1. Landform
        // ====================================================================================================

        [Header("지형")]
        [Range(0, 5)]
        [Tooltip("섬에 세울 봉우리 수입니다.\n\n" +
                 "0이면 고도가 해안 거리만 따라가 웨딩케이크가 됩니다. " +
                 "봉우리가 여럿이면 그 사이에 안부가 생기고, 그것이 계곡의 출발점이 됩니다.")]
        public int PeakCount = 2;

        [Range(0, 6)]
        [Tooltip("팔 계곡의 수입니다.\n\n" +
                 "물이 판 골짜기는 높은 곳에서 시작해 내려가기만 하고, 아래로 갈수록 합쳐지며, " +
                 "바다에서 끝납니다. 그 위상을 지켜야 파인 것으로 읽힙니다.")]
        public int ValleyCount = 3;

        // ====================================================================================================
        // 3. Content
        // ====================================================================================================

        [Header("배치물")]
        [Range(0, 8)]
        [Tooltip("섬에 배치할 가옥 수입니다. 방어 목표이자 보상원입니다.")]
        public int HouseCount = 3;

        [Range(1, 8)]
        [Tooltip("적이 상륙할 수 있는 해안 구역의 수입니다. 전선 분산 압박의 핵심 변수입니다.")]
        public int LandingZoneCount = 4;

        [Range(1, 6)]
        [Tooltip("가옥끼리 최소로 떨어져야 하는 격자 거리입니다.")]
        public int HouseMinSpacing = 4;

        // ====================================================================================================
        // 4. Determinism
        // ====================================================================================================

        [Header("결정성")]
        [Tooltip("생성 시드입니다. 0이면 실행할 때마다 무작위 시드를 사용합니다.")]
        public int Seed = 0;

        // ====================================================================================================
        // 5. Factory
        // ====================================================================================================

        /// <summary>
        /// 에셋 없이 코드로 기본 설정을 만듭니다. 부트스트랩의 폴백 경로입니다.
        /// </summary>
        public static IslandSettings CreateDefault()
        {
            var settings = CreateInstance<IslandSettings>();
            settings.name = "IslandSettings_Default";
            return settings;
        }
    }
}
