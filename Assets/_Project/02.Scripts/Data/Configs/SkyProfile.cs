using UnityEngine;

namespace SRPG.Data
{
    /// <summary>
    /// 전장 위의 하늘입니다. 지금은 지나가는 구름의 그늘이 전부입니다.
    ///
    /// <b>왜 에셋이어야 하는가</b>
    ///
    /// 이 값들은 <c>BattlefieldView</c> 에 직렬화 필드로 붙어 있었습니다.
    /// 그런데 그 컴포넌트는 런타임에 <c>AddComponent</c> 되므로
    /// <b>인스펙터에 뜰 기회가 없습니다</b> — 재생 중에만 존재하는 오브젝트라
    /// 구름을 짙게 해 보려면 코드를 고치고 컴파일해야 했습니다.
    ///
    /// <see cref="GrassProfile"/> 가 정확히 같은 이유로 먼저 떨어져 나왔습니다.
    /// 같은 함정에 두 번 빠진 셈이라 같은 방식으로 꺼냅니다.
    ///
    /// <b>왜 들판 프로필에 넣지 않는가</b>
    ///
    /// 구름은 풀의 성질이 아닙니다. 지형·물·풀·병사 <b>넷 모두</b>가 같은 그늘을 받고,
    /// 그래서 어느 한 종에 매달 수 없습니다. 하늘은 그 넷 위에 있습니다.
    ///
    /// <b>없어도 됩니다.</b> 연결되지 않으면 <see cref="CreateDefault"/> 가
    /// 지금까지의 모습을 그대로 만들어 냅니다.
    /// </summary>
    [CreateAssetMenu(fileName = "SkyProfile_", menuName = "SRPG/하늘", order = 44)]
    public sealed class SkyProfile : ScriptableObject
    {
        // ====================================================================================================
        // 1. Inspector
        // ====================================================================================================

        [Header("구름 그늘")]
        [Range(0f, 0.8f)]
        [Tooltip("구름 그늘이 빛에서 덜어 내는 양입니다. 0이면 구름이 꺼집니다.\n\n" +
                 "<b>계단 하나가 대략 1/계단수 입니다.</b> 툰 계단이 넷이면 0.25가 정확히 한 칸이라, " +
                 "그보다 작으면 자리에 따라 걸렸다 안 걸렸다 합니다.\n" +
                 "깊게 하면 연출은 살지만 지형이 색으로 말하던 '갈 수 있는 곳'이 지나가는 그늘에 묻힙니다.")]
        public float Depth = 0.34f;

        [Range(0.002f, 0.1f)]
        [Tooltip("구름 덩어리의 크기입니다. <b>작을수록 큰 구름</b>입니다 — 좌표에 곱하는 값이라 그렇습니다.")]
        public float Scale = 0.012f;

        [Range(0f, 2f)]
        [Tooltip("구름이 흘러가는 속도입니다.\n" +
                 "느리게 두면 한참 봐야 지나가는 것이 보입니다. 걸려 있는지 확인할 때는 잠깐 올려 보십시오.")]
        public float Speed = 0.35f;

        [Tooltip("구름이 흘러가는 방향입니다. 바람과 같은 쪽이어야 자연스럽습니다.")]
        public Vector2 Direction = new Vector2(1f, 0.35f);

        [Range(0f, 1f)]
        [Tooltip("하늘을 덮는 정도의 기준선입니다. 높이면 맑고, 낮추면 흐립니다.")]
        public float Coverage = 0.52f;

        [Range(0.01f, 0.5f)]
        [Tooltip("구름 가장자리의 부드러움입니다.\n" +
                 "작게 두면 경계가 또렷해 그림자처럼 읽히고, 크게 두면 뭉근하게 번집니다.")]
        public float Softness = 0.16f;

        [Min(1f)]
        [Tooltip("구름이 떠 있는 높이입니다.\n" +
                 "그늘은 이 높이의 구름층에 광원 방향으로 역추적해 맺힙니다. " +
                 "지형보다 충분히 위여야 해가 기울 때 그늘이 옆으로 길게 눕습니다.")]
        public float Height = 60f;

        // ====================================================================================================
        // 2. Factory
        // ====================================================================================================

        /// <summary>
        /// 에셋 없이 코드로 기본 하늘을 만듭니다.
        /// </summary>
        /// <returns>필드 초기값이 그대로 담긴 하늘입니다. 에셋으로 저장되지 않습니다.</returns>
        public static SkyProfile CreateDefault()
        {
            var profile = CreateInstance<SkyProfile>();
            profile.name = "SkyProfile_Default";

            return profile;
        }
    }
}
